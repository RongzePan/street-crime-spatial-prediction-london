# but getLogger is retained)
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
log = logging.getLogger(__name__)

# ── Update CRIME_TYPES to align with config.STREET_CRIME_TYPES ──────────────
# Replaces the original CRIME_TYPES dictionary
CRIME_TYPES = {
    # Street crime focus types (matching the four keys in STREET_CRIME_TYPES)
    "theft_from_person": ["theft-from-the-person"],
    "robbery":           ["robbery"],
    "violence_sexual":   ["violence-and-sexual-offences"],
    "public_order":      ["public-order"],
    # Other categories (retained to maintain crime_count completeness)
    "burglary":  ["burglary"],
    "vehicle":   ["vehicle-crime"],
    "drugs":     ["drugs"],
    "other":     ["anti-social-behaviour", "criminal-damage-arson",
                  "other-crime", "weapons", "possession-of-weapons",
                  "shoplifting", "bicycle-theft", "other-theft"],
}

def load_crimes(police_dir: Path) -> gpd.GeoDataFrame:
    """Read all monthly Parquet files and return a GeoDataFrame containing coordinates."""
    dfs = []
    for f in sorted(police_dir.glob("crimes_*.parquet")):
        dfs.append(pd.read_parquet(f))

    if not dfs:
        raise FileNotFoundError(
            f"No crimes_*.parquet files found in {police_dir}. "
            "Please run python main.py --stage download first."
        )

    df = pd.concat(dfs, ignore_index=True)
    df = df.dropna(subset=["latitude", "longitude"])
    df["month"] = pd.to_datetime(df["month"], format="%Y-%m")

    cat_map = {v: k for k, vs in CRIME_TYPES.items() for v in vs}
    df["crime_group"] = df["category"].map(cat_map).fillna("other")

    gdf = gpd.GeoDataFrame(
        df,
        geometry=gpd.points_from_xy(df["longitude"], df["latitude"]),
        crs=CRS_WGS84,
    ).to_crs(CRS_BNG)

    return gdf[["id", "month", "category", "crime_group", "geometry"]]

def spatial_join(crimes: gpd.GeoDataFrame,
                 lsoa: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    """
    Spatial join: match each crime record to its containing LSOA.

    Fix 1: The original code requested LAD21NM, but the BGC_V5 service
    contains no LAD fields. Use LSOA21NM (LSOA name) as a substitute to
    satisfy subsequent labelling requirements.
    area_m2 is pre‑computed and written by download_geodata.py when saving
    the GPKG, so it is directly available upon loading.
    """
    # ── Defensive check: print actual available columns ────────────────
    lsoa_cols = list(lsoa.columns)
    print(f"  LSOA actual columns: {lsoa_cols}")

    # Verify required columns exist
    required = ["LSOA21CD", "area_m2"]
    missing = [c for c in required if c not in lsoa_cols]
    if missing:
        raise KeyError(
            f"LSOA data missing required columns: {missing}\n"
            f"Actual columns: {lsoa_cols}\n"
            f"Please ensure data/raw/boundaries/lsoa_2021_london.gpkg was "
            f"generated by the latest version of download_geodata.py."
        )

    # Fix 1: use LSOA21NM instead of the removed LAD21NM
    name_col = "LSOA21NM" if "LSOA21NM" in lsoa_cols else None
    join_cols = ["LSOA21CD", "area_m2", "geometry"]
    if name_col:
        join_cols = ["LSOA21CD", name_col, "area_m2", "geometry"]

    # Ensure CRS consistency
    if crimes.crs != lsoa.crs:
        print(f"  CRS mismatch; converting: crimes={crimes.crs} → lsoa={lsoa.crs}")
        crimes = crimes.to_crs(lsoa.crs)

    joined = gpd.sjoin(
        crimes, lsoa[join_cols],
        how="inner", predicate="within"
    )
    return joined.drop(columns=["index_right"])


def build_panel(crimes_joined: gpd.GeoDataFrame,
                lsoa: gpd.GeoDataFrame,
                pop: pd.DataFrame) -> pd.DataFrame:
    """
    Build the full panel dataset:
    rows = LSOA × month, columns = crime counts by category + crime rates.

    Fix 2: use LSOA21NM for area merge, remove dependency on LAD21NM.
    Fix 3: rename population column from population_2020 to population_est.
    """
    all_months = pd.date_range(
        start=f"{START_YEAR}-{START_MONTH:02d}",
        end=f"{END_YEAR}-{END_MONTH:02d}",
        freq="MS"
    )
    all_lsoas = lsoa["LSOA21CD"].unique()
    idx = pd.MultiIndex.from_product(
        [all_lsoas, all_months], names=["lsoa_code", "month"]
    )
    panel = pd.DataFrame(index=idx).reset_index()

    # Aggregate total crime count
    total = (crimes_joined
             .groupby(["LSOA21CD", "month"])
             .size()
             .reset_index(name="crime_count"))
    total.columns = ["lsoa_code", "month", "crime_count"]

    # Aggregate by category
    by_type = (crimes_joined
               .groupby(["LSOA21CD", "month", "crime_group"])
               .size()
               .unstack(fill_value=0)
               .reset_index())
    by_type.columns.name = None
    by_type.columns = (["lsoa_code", "month"] +
                       [f"n_{c}" for c in by_type.columns[2:]])

    panel = (panel
             .merge(total,   on=["lsoa_code", "month"], how="left")
             .merge(by_type, on=["lsoa_code", "month"], how="left")
             .fillna(0))

    # Fix 3: population_2020 → population_est
    # Compatible with both old and new versions of download_population column names
    pop_col = next(
        (c for c in pop.columns
         if c in ["population_est", "population_2020", "population"]),
        None
    )
    if pop_col is None:
        print(f"  ⚠ Population data lacks a population value column; columns: {list(pop.columns)}")
    else:
        if pop_col != "population_est":
            pop = pop.rename(columns={pop_col: "population_est"})

        # Normalise both sides: strip whitespace and convert to uppercase
        # (to avoid hidden characters or case mismatches)
        pop_norm = pop[["lsoa_code", "population_est"]].copy()
        pop_norm["lsoa_code"] = (
            pop_norm["lsoa_code"].astype(str).str.strip().str.upper()
        )
        panel["lsoa_code"] = (
            panel["lsoa_code"].astype(str).str.strip().str.upper()
        )

        # Diagnostic output
        panel_codes = set(panel["lsoa_code"].unique())
        pop_codes   = set(pop_norm["lsoa_code"].unique())
        common      = panel_codes & pop_codes
        print(f"  Population merge diagnostic: "
              f"{len(common)} / {len(panel_codes)} LSOAs matched")

        if len(common) == 0:
            print("  ⚠ No matches! Code sample comparison:")
            print(f"    panel first 3:  {sorted(list(panel_codes))[:3]}")
            print(f"    pop first 3:    {sorted(list(pop_codes))[:3]}")
            print("  → Possible cause: population Parquet was generated from an older SAPE file (2011 LSOA codes).")
            print("  → Solution: delete the following files and re-run:")
            print("      data/raw/population/lsoa_population.parquet")
            print("      data/raw/population/*.xlsx")
            print("  → crime_rate_1k will remain NaN; this does not affect LSTM/KDE modelling (we use crime_density).")
        elif len(common) < len(panel_codes) * 0.5:
            print(f"  ⚠ Match rate only {len(common)/len(panel_codes):.0%}, "
                  f"population data may be from a different year than the boundary file.")

        panel = panel.merge(
            pop_norm, on="lsoa_code", how="left"
        )
        panel["crime_rate_1k"] = (
            panel["crime_count"]
            / panel["population_est"].replace(0, np.nan)
            * 1000
        )

    # Fix 2: area and name columns, dynamically adapting to presence of LSOA21NM
    lsoa_cols = list(lsoa.columns)
    area_merge_cols = ["LSOA21CD", "area_m2"]
    if "LSOA21NM" in lsoa_cols:
        area_merge_cols.append("LSOA21NM")

    area = (lsoa[area_merge_cols]
            .rename(columns={"LSOA21CD": "lsoa_code"}))
    panel = panel.merge(area, on="lsoa_code", how="left")

    # ── Column name migration: handle legacy naming differences ──────────
    # Old CRIME_TYPES keys → new standard keys
    LEGACY_COL_MAP = {
        "n_violence_sexual": "n_violent",      # 旧键: "violent"
        "n_theft_from_person": "n_theft",      # 旧键: "theft"（备用）
        "n_public_order": "n_public-order",    # 旧键: 含连字符
    }
    for new_col, old_col in LEGACY_COL_MAP.items():
        if new_col not in panel.columns and old_col in panel.columns:
            panel = panel.rename(columns={old_col: new_col})
            log.info(f"  ↔ 列名迁移: '{old_col}' → '{new_col}'")

    # ── Diagnostic: print all n_* columns ──────────────────────────────────
    n_cols = sorted([c for c in panel.columns if c.startswith("n_")])
    log.info(f"  n_* 列（共{len(n_cols)}个）: {n_cols}")

    # ── Spatial density columns for each street crime type ──────────────
    from config import STREET_CRIME_TYPES
    for ct_key in STREET_CRIME_TYPES:
        n_col = f"n_{ct_key}"
        if n_col in panel.columns:
            panel[f"density_{ct_key}"] = (
                    panel[n_col]
                    / panel["area_m2"].replace(0, np.nan)
                    * 1e6
            )
            non_zero = (panel[f"density_{ct_key}"] > 0).sum()
            log.info(f"  Computed density_{ct_key} (non-zero rows: {non_zero:,})")
        else:
            log.warning(
                f"  ⚠ Column '{n_col}' does not exist; cannot compute density_{ct_key}\n"
                f"    Available n_* columns: {n_cols}\n"
                f"    → Please verify CRIME_TYPES keys and delete cached panel to rebuild."
            )

    panel["crime_density"] = (
        panel["crime_count"] /
        panel["area_m2"].replace(0, np.nan) * 1e6  # per km²
    )

    # Temporal features
    panel["month_of_year_sin"] = np.sin(
        2 * np.pi * panel["month"].dt.month / 12)
    panel["month_of_year_cos"] = np.cos(
        2 * np.pi * panel["month"].dt.month / 12)
    panel["year_norm"] = (
        (panel["month"].dt.year - START_YEAR) /
        max(END_YEAR - START_YEAR, 1)
    )

    return panel.sort_values(["lsoa_code", "month"]).reset_index(drop=True)


def run():

    # ── 面板结构验证：自动检测并清除过时缓存 ───────────────────────
    panel_path = PROC_DIR / "panel.parquet"
    if panel_path.exists():
        try:
            _check = pd.read_parquet(panel_path)
            # 当前版本必须包含的列
            required_cols = {
                "n_theft_from_person", "n_robbery",
                "n_violence_sexual",   "n_public_order",
                "density_theft_from_person", "density_robbery",
            }
            missing = required_cols - set(_check.columns)
            if missing:
                print(f"\n  ⚠ 检测到面板结构过时（缺少: {missing}）")
                print(f"  → 自动删除旧面板，即将重新生成...\n")
                panel_path.unlink()
            else:
                print(f"  ✓ 面板结构验证通过（{_check.shape[1]} 列，"
                      f"{_check.shape[0]:,} 行）")
        except Exception as e:
            print(f"  面板读取异常（{e}），重新生成...")
            panel_path.unlink()

    print("Loading crime records...")
    crimes = load_crimes(RAW_DIR / "police")
    print(f"  {len(crimes):,} street-level crimes loaded")

    print("Loading LSOA boundaries...")
    lsoa = gpd.read_file(RAW_DIR / "boundaries" / "lsoa_2021_london.gpkg")
    print(f"  {len(lsoa):,} LSOAs loaded, CRS: {lsoa.crs}")
    print(f"  Columns: {list(lsoa.columns)}")

    print("Loading population data...")
    pop = pd.read_parquet(
        RAW_DIR / "population" / "lsoa_population.parquet")
    print(f"  {len(pop):,} LSOAs, columns: {list(pop.columns)}")

    print("Spatial join (crime points → LSOAs)...")
    crimes_j = spatial_join(crimes, lsoa)
    print(f"  {len(crimes_j):,} crimes matched to London LSOAs")

    if len(crimes_j) == 0:
        raise ValueError(
            "Spatial join returned 0 matches! Please check:\n"
            "1. Do crime coordinates cover the London area?\n"
            "2. Does the LSOA boundary indeed cover Greater London (BNG_E/N bounding‑box filter)?\n"
            f"   LSOA CRS: {lsoa.crs}\n"
            f"   LSOA extent: {lsoa.total_bounds}"
        )

    print("Building panel dataset...")
    panel = build_panel(crimes_j, lsoa, pop)

    out = PROC_DIR / "panel.parquet"
    panel.to_parquet(out, index=False)

    # Summary statistics
    months_n = panel["month"].nunique()
    lsoas_n  = panel["lsoa_code"].nunique()
    print(f"\nPanel saved: {panel.shape} → {out}")
    print(f"  LSOAs: {lsoas_n:,}  ×  Months: {months_n}")
    print(f"  Average monthly total crime: {panel.groupby('month')['crime_count'].sum().mean():.0f}")
    print(f"  Mean crime rate (per 1,000): {panel['crime_rate_1k'].mean():.2f}")
    print(panel[["crime_count", "crime_rate_1k",
                 "crime_density"]].describe().round(3))
    return panel

if __name__ == "__main__":
    run()